const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'chrome'});
 const ctx=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block'});
 const page=await ctx.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',msg=>{if(msg.text().includes('[knowledge-sheet]'))console.log(msg.text())});
 try{
  await page.goto(process.env.TEST_URL||'http://127.0.0.1:8000/');
  await page.waitForFunction(()=>typeof devicePositionReady!=='undefined'&&devicePositionReady);
  await page.evaluate(()=>{activateModule('data');openKnowledge('data-topic-course-07-fraction-mix')});
  await page.waitForTimeout(400);
  const fab=page.locator('#knowledgeDirectoryFab'),sheet=page.locator('#knowledgeDirectorySheet');
  assert.equal(await page.locator('#knowledgeSidebar').evaluate(e=>getComputedStyle(e).display),'none');
  assert.ok(await fab.isVisible());
  console.log('[knowledge-sheet-test] fab style',await fab.evaluate(e=>({position:getComputedStyle(e).position,rect:e.getBoundingClientRect().toJSON(),parent:e.parentElement.id,scrollY})));
  await page.evaluate(()=>{const e=document.getElementById('kb-structured-fraction-mix-flexible-recognition');document.documentElement.style.scrollBehavior='auto';window.scrollTo({top:scrollY+e.getBoundingClientRect().top-60,behavior:'instant'})});
  await page.waitForTimeout(100);
  const before=await page.evaluate(()=>scrollY);
  await fab.click();await page.waitForTimeout(250);
  console.log('[knowledge-sheet-test] after open',await page.evaluate(()=>scrollY));
  assert.ok(await sheet.isVisible());
  const rect=await sheet.boundingBox();
  assert.ok(rect.width>=389&&rect.height>=500&&rect.height<=600);
  assert.equal(await page.locator('#knowledgeSidebar').evaluate(e=>e.parentElement.id),'knowledgeSheetContent');
  assert.equal(await page.evaluate(()=>document.getElementById('knowledgeView').inert),true);
  await page.locator('#knowledgeSearch').fill('增速的累积');
  console.log('[knowledge-sheet-test] after search fill',await page.evaluate(()=>scrollY));
  assert.equal(await page.evaluate(()=>selectedTopic),'data-topic-course-07-fraction-mix');
  await page.locator('#knowledgeDirectoryClose').click();
  await page.waitForTimeout(260);
  console.log('[knowledge-sheet-test] after close',await page.evaluate(()=>scrollY));
  const afterClose=await page.evaluate(()=>scrollY);
  assert.ok(Math.abs(afterClose-before)<3,`Closing restores exact background scroll (before=${before}, after=${afterClose})`);
  await fab.click();await page.waitForTimeout(250);
  await page.locator('#knowledgeNav [data-knowledge-section="data-growth-rate"]').click();
  assert.equal(await page.evaluate(()=>selectedTopic),'data-topic-course-07-fraction-mix');
  await page.locator('#knowledgeNav [data-knowledge-topic="data-topic-course-05-growth-decomposition"]').click();
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(()=>selectedTopic),'data-topic-course-05-growth-decomposition');
  assert.equal(await sheet.isVisible(),false);
  await fab.click();await page.waitForTimeout(250);
  await page.locator('#knowledgeNav [data-knowledge-section="data-fraction-share"]').click();
  await page.locator('#knowledgeNav [data-knowledge-topic="data-topic-course-07-fraction-mix"]').click();
  await page.waitForTimeout(300);
  assert.ok(Math.abs(await page.evaluate(()=>scrollY)-before)<35,'Lesson 7 restores saved reading position');
  await fab.click();await page.waitForTimeout(250);
  await page.keyboard.press('Escape');await page.waitForTimeout(250);
  assert.equal(await sheet.isVisible(),false);
  await page.setViewportSize({width:1024,height:768});
  assert.equal(await fab.isVisible(),false);
  assert.ok(await page.locator('#knowledgeSidebar').isVisible());
  assert.deepEqual(errors,[]);
  console.log('Mobile knowledge directory: full width, search, scroll lock, navigation, bookmarks, desktop sidebar OK');
 }finally{await ctx.close();await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
